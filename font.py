def tile_from_pixels(px):
    """px: 8 rows of 8 colour indexes -> 32 bytes of tile data"""
    out = bytearray(32)
    for pair, base in ((0, 0x10), (1, 0x18), (2, 0x00), (3, 0x08)):
        for y in range(8):
            left, right = px[y][pair*2], px[y][pair*2+1]
            out[base+y] = (right << 4) | left
    return out

def make_font():
    tiles = bytearray(0x4000)               # 512 blank tiles
    for ch, rows in GLYPHS.items():
        px = [[0]*8 for _ in range(8)]
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == '#':
                    px[y][x+1] = 1          # colour 1, one pixel left margin
        tiles[ord(ch)*32:ord(ch)*32+32] = tile_from_pixels(px)
    # progress bar cells: outline (colour 2) and filled (colour 3)
    empty = [[0]*8 for _ in range(8)]
    full = [[0]*8 for _ in range(8)]
    for y in range(1, 7):
        for x in range(0, 7):
            edge = y in (1, 6) or x in (0, 6)
            empty[y][x] = 2 if edge else 0
            full[y][x] = 2 if edge else 3
    tiles[0x10*32:0x10*32+32] = tile_from_pixels(empty)
    tiles[0x11*32:0x11*32+32] = tile_from_pixels(full)
    return bytes(tiles)

